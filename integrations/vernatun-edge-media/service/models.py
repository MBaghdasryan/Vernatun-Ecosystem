from __future__ import annotations

from datetime import datetime
from typing import Literal, Optional
from urllib.parse import urlsplit

from pydantic import BaseModel, Field, field_validator


StreamState = Literal[
    "IDLE",
    "STARTING",
    "LIVE",
    "STOPPING",
    "FAILED",
    "OFFLINE",
]


class CameraStatus(BaseModel):
    deviceId: str
    sourceType: str
    online: bool
    videoAvailable: bool
    width: int = 0
    height: int = 0
    fps: float = 0.0
    streamState: StreamState = "OFFLINE"
    activeMediaSessions: int = 0
    activeViewers: int = 0
    lastFrameAt: Optional[str] = None
    location: Optional[str] = None
    zone: Optional[str] = None
    capabilities: list[str] = Field(default_factory=list)


class IceServer(BaseModel):
    urls: str | list[str]
    username: Optional[str] = None
    credential: Optional[str] = None


class MediaSessionCreate(BaseModel):
    sessionId: str
    deviceId: str
    protocol: Literal["WEBRTC"] = "WEBRTC"

    # WHIP ingest endpoint generated by Cloud Media Gateway.
    publishUrl: str
    publisherToken: str = Field(min_length=8, max_length=4096)
    expiresAt: datetime

    iceServers: list[IceServer] = Field(default_factory=list)

    @field_validator("publishUrl")
    @classmethod
    def validate_publish_url(cls, value: str) -> str:
        parsed = urlsplit(value)
        host = (parsed.hostname or "").lower()
        if (
            parsed.scheme != "https"
            or not host
            or parsed.username
            or parsed.password
            or parsed.fragment
            or parsed.port not in (None, 443)
        ):
            raise ValueError("publishUrl must be a credential-free HTTPS URL")
        return value

    @field_validator("expiresAt")
    @classmethod
    def require_timezone(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("expiresAt must include a timezone")
        return value


class MediaSessionViewersUpdate(BaseModel):
    activeViewers: int = Field(ge=0, le=10000)


class MediaSessionStatus(BaseModel):
    sessionId: str
    deviceId: str
    state: StreamState
    protocol: str = "WEBRTC"
    startedAt: Optional[str] = None
    stoppedAt: Optional[str] = None
    failureCode: Optional[str] = None
    failureMessage: Optional[str] = None
    activeViewers: int = 0
