import pg from 'pg';
import {mkdtemp,chmod,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomBytes} from 'node:crypto';
import {privateStorageLocation} from './private-files.js';
import {backupLocation,sha256,validateManifest,type BackupManifest} from './backup-format.js';
import {identifier,postgresTool,referencedFiles,tableFingerprints} from './backup-postgres.js';

export type RestoreContext={
  manifest:BackupManifest;db:pg.Client;connectionString:string;testRun:string;
};
// No caller-supplied target DB or live object prefix is accepted.
// The callback can inspect the restored app in isolation; resources are temporary.
export async function withIsolatedRestore<T>(id:string,inspect:(context:RestoreContext)=>Promise<T>){
  if(process.env.NODE_ENV==='production')throw new Error('Restore drills cannot run in production');
  const connection=process.env.DATABASE_URL;
  if(!connection)throw new Error('DATABASE_URL required');
  const source=backupLocation(id),storage=privateStorageLocation();
  const manifest=validateManifest(JSON.parse((await source.bucket.file(source.prefix+'manifest.json').download())[0].toString('utf8')));
  if(manifest.id!==id)throw new Error('Backup ID mismatch');
  const download=async(name:string,expected:{bytes:number;sha256:string})=>{
    const bytes=(await source.bucket.file(source.prefix+name).download())[0];
    if(bytes.length!==expected.bytes||sha256(bytes)!==expected.sha256)throw new Error('Backup checksum mismatch');
    return bytes;
  };
  // Verify the complete set before creating any restored resource.
  const dump=await download('database.dump',manifest.dump);
  const files=new Map<string,Buffer>();
  for(const f of manifest.files)files.set(`${f.kind}/${f.key}`,await download(`files/${f.kind}/${f.key}`,f));
  const work=await mkdtemp(join(tmpdir(),'vernatun-restore-'));
  await chmod(work,0o700);
  const name='vernatun_restore_'+randomBytes(10).toString('hex');
  const testRun='qa_'+randomBytes(10).toString('hex');
  const parent=storage.prefix.replace(/\/vernatun(?:-test\/qa_[a-f0-9]{20})?\/$/,'');
  const prefix=`${parent}/vernatun-test/${testRun}/`;
  const target=new URL(connection);target.pathname='/'+name;
  target.searchParams.set('options',`-c search_path=${manifest.schema},public`);
  const admin=new pg.Client({connectionString:connection});
  const db=new pg.Client({connectionString:target.toString()});
  const createdObjects:string[]=[];
  let createdDatabase=false,connected=false,adminConnected=false;
  try{
    await writeFile(join(work,'database.dump'),dump,{mode:0o600,flag:'wx'});
    await admin.connect();adminConnected=true;
    await admin.query(`CREATE DATABASE ${identifier(name)} TEMPLATE template0`);
    createdDatabase=true;
    await postgresTool('pg_restore',target.toString(),['--exit-on-error','--single-transaction','--no-owner','--no-acl',`--dbname=${name}`,join(work,'database.dump')]);
    await db.connect();connected=true;
    const tables=(await db.query('SELECT tablename AS name FROM pg_tables WHERE schemaname=$1 ORDER BY tablename',[manifest.schema])).rows.map(r=>r.name);
    if(JSON.stringify(await tableFingerprints(db,manifest.schema,tables))!==JSON.stringify(manifest.tables))
      throw new Error('Restored database fingerprint mismatch');
    const refs=await referencedFiles(db,manifest.schema);
    if(refs.length!==manifest.files.length||refs.some(f=>!manifest.files.find(x=>x.kind===f.kind&&x.key===f.key&&x.mediaType===f.media_type)))
      throw new Error('Restored metadata/file set mismatch');
    for(const f of manifest.files){
      const key=`${prefix}${f.kind}/${f.key}`,object=storage.bucket.file(key);
      createdObjects.push(key); // Include ambiguous write responses in isolated cleanup.
      await object.save(files.get(`${f.kind}/${f.key}`)!,{resumable:false,validation:'crc32c',
        preconditionOpts:{ifGenerationMatch:0},
        metadata:{contentType:f.mediaType,cacheControl:'private, no-store',metadata:f.metadata}});
      if(sha256((await object.download())[0])!==f.sha256)throw new Error('Restored file checksum mismatch');
    }
    return await inspect({manifest,db,connectionString:target.toString(),testRun});
  }finally{
    // All targets were generated by this invocation. Never touch the source.
    try{
      if(connected)await db.end();
      if(createdDatabase)await admin.query(`DROP DATABASE ${identifier(name)} WITH (FORCE)`);
      for(const key of createdObjects)await storage.bucket.file(key).delete({ignoreNotFound:true});
    }finally{
      if(adminConnected)await admin.end();
      await rm(work,{recursive:true,force:true});
    }
  }
}
